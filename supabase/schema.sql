-- -------------------------------------------------------------
-- ENUM / tabel utama
-- -------------------------------------------------------------

do $$
begin
  create type public.user_role as enum ('student', 'staff');
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.report_status as enum (
    'Belum Ditemukan',
    'Sedang Ditelusuri',
    'Barang Ditemukan',
    'Sudah Dikembalikan'
  );
exception
  when duplicate_object then null;
end
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  nim text unique check (nim is null or nim ~ '^[A-Za-z0-9.-]+$'),
  username text unique,
  study_program text not null default '' check (char_length(study_program) <= 120),
  role public.user_role not null default 'student',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  report_number text unique,
  user_id uuid not null references public.profiles(id) on delete cascade,
  item_name text not null check (char_length(item_name) between 1 and 120),
  category text not null check (category in ('Elektronik','Dokumen','Aksesori','Pakaian','Kendaraan','Lainnya')),
  description text not null check (char_length(description) between 1 and 1200),
  photo text,
  location text not null check (char_length(location) between 1 and 180),
  lost_at timestamptz not null,
  contact text not null check (char_length(contact) between 1 and 40),
  status public.report_status not null default 'Belum Ditemukan',
  staff_note text not null default '' check (char_length(staff_note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.report_updates (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports(id) on delete cascade,
  staff_id uuid references public.profiles(id) on delete set null,
  status public.report_status not null,
  note text not null default '' check (char_length(note) <= 500),
  created_at timestamptz not null default now()
);

create index if not exists profiles_role_idx on public.profiles(role);
create index if not exists reports_user_id_idx on public.reports(user_id);
create index if not exists reports_status_idx on public.reports(status);
create index if not exists reports_created_at_idx on public.reports(created_at desc);
create index if not exists reports_item_name_idx on public.reports using gin (to_tsvector('simple', item_name));
create index if not exists report_updates_report_id_idx on public.report_updates(report_id, id);

