-- -------------------------------------------------------------
-- Membuat profile otomatis setelah user Auth mendaftar
-- -------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, nim, study_program)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, 'Pengguna'), '@', 1)),
    nullif(new.raw_user_meta_data ->> 'nim', ''),
    coalesce(new.raw_user_meta_data ->> 'studyProgram', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- -------------------------------------------------------------
-- Keamanan role: mahasiswa tidak boleh menaikkan dirinya menjadi staff
-- -------------------------------------------------------------

create or replace function public.protect_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.id and old.role = 'student' and new.role <> old.role then
    raise exception 'Mahasiswa tidak dapat mengubah role sendiri';
  end if;
  if auth.uid() = old.id and new.id <> old.id then
    raise exception 'ID profile tidak dapat diubah';
  end if;
  if auth.uid() = old.id and new.nim is distinct from old.nim then
    raise exception 'NIM tidak dapat diubah dari aplikasi';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_privileges on public.profiles;
create trigger protect_profile_privileges
before update on public.profiles
for each row execute function public.protect_profile_privileges();

-- -------------------------------------------------------------
-- Nomor laporan otomatis: LKB-TAHUN-ID
-- -------------------------------------------------------------

create or replace function public.assign_report_number()
returns trigger
language plpgsql
as $$
begin
  if new.report_number is null or btrim(new.report_number) = '' then
    new.report_number := 'LKB-' || to_char(coalesce(new.created_at, now()), 'YYYY') || '-' || lpad(new.id::text, 4, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists reports_assign_number on public.reports;
create trigger reports_assign_number
before insert on public.reports
for each row execute function public.assign_report_number();

