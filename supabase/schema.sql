values ('report-photos', 'report-photos', true)
on conflict (id) do update set public = true;

drop policy if exists report_photos_public_read on storage.objects;
create policy report_photos_public_read
on storage.objects for select
using (bucket_id = 'report-photos');

drop policy if exists report_photos_authenticated_insert on storage.objects;
create policy report_photos_authenticated_insert
on storage.objects for insert to authenticated
with check (
  bucket_id = 'report-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists report_photos_owner_delete on storage.objects;
create policy report_photos_owner_delete
on storage.objects for delete to authenticated
using (
  bucket_id = 'report-photos'
  and (owner_id = auth.uid() or public.is_staff())
);

