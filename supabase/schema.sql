create or replace function public.public_search_reports(p_query text)
returns table (
  id bigint,
  report_number text,
  item_name text,
  category text,
  description text,
  photo text,
  location text,
  lost_at timestamptz,
  status public.report_status,
  staff_note text,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, r.report_number, r.item_name, r.category, r.description, r.photo,
         r.location, r.lost_at, r.status, r.staff_note, r.created_at, r.updated_at
  from public.reports r
  where r.report_number ilike '%' || p_query || '%'
     or r.item_name ilike '%' || p_query || '%'
     or r.category ilike '%' || p_query || '%'
  order by r.created_at desc
  limit 20;
$$;

create or replace function public.public_report_detail(p_report_number text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  r jsonb;
  u jsonb;
begin
  select jsonb_build_object(
    'id', x.id,
    'report_number', x.report_number,
    'item_name', x.item_name,
    'category', x.category,
    'description', x.description,
    'photo', x.photo,
    'location', x.location,
    'lost_at', x.lost_at,
    'status', x.status,
    'staff_note', x.staff_note,
    'created_at', x.created_at,
    'updated_at', x.updated_at
  ) into r
  from public.reports x
  where x.report_number ilike p_report_number
  limit 1;

  if r is null then
    raise exception 'Laporan tidak ditemukan';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'status', ru.status,
    'note', ru.note,
    'createdAt', ru.created_at
  ) order by ru.id), '[]'::jsonb)
  into u
  from public.report_updates ru
  where ru.report_id = (r ->> 'id')::bigint;

  return jsonb_build_object('report', r, 'updates', u);
end;
$$;

create or replace function public.public_found_reports()
returns table (
  id bigint,
  report_number text,
  item_name text,
  category text,
  description text,
  photo text,
  location text,
  lost_at timestamptz,
  status public.report_status,
  staff_note text,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, r.report_number, r.item_name, r.category, r.description, r.photo,
         r.location, r.lost_at, r.status, r.staff_note, r.created_at, r.updated_at
  from public.reports r
  where r.status = 'Barang Ditemukan'
  order by r.updated_at desc
  limit 30;
$$;

-- Login menggunakan email, NIM, atau username.
-- Catatan: RPC ini hanya mengembalikan email yang cocok secara exact.
create or replace function public.resolve_login_email(p_identifier text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select u.email
  from auth.users u
  join public.profiles p on p.id = u.id
  where lower(u.email) = lower(trim(p_identifier))
     or lower(coalesce(p.username, '')) = lower(trim(p_identifier))
     or lower(coalesce(p.nim, '')) = lower(trim(p_identifier))
  limit 1;
$$;

revoke all on function public.public_search_reports(text) from public;
grant execute on function public.public_search_reports(text) to anon, authenticated;
revoke all on function public.public_report_detail(text) from public;
grant execute on function public.public_report_detail(text) to anon, authenticated;
revoke all on function public.public_found_reports() from public;
grant execute on function public.public_found_reports() to anon, authenticated;
revoke all on function public.resolve_login_email(text) from public;
grant execute on function public.resolve_login_email(text) to anon, authenticated;

